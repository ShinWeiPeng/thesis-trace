def compare_documents(manifest: dict[str, Any], manifest_path: Path) -> list[tuple[str, str, str]]:
    architecture_root = manifest_path.parent
    expected = render_documents(manifest)
    diagnostics: list[tuple[str, str, str]] = []
    for relative, content in expected.items():
        destination = architecture_root / relative
        if not destination.is_file():
            diagnostics.append(("DOC001", relative.as_posix(), "generated architecture document is missing"))
        elif destination.read_text(encoding="utf-8") != content:
            diagnostics.append(("DOC002", relative.as_posix(), "generated architecture document is stale"))
    generated_root = architecture_root / "generated"
    if generated_root.is_dir():
        for path in generated_root.rglob("*.md"):
            relative = path.relative_to(architecture_root)
            if relative not in expected and relative not in EXTERNALLY_GENERATED_DOCUMENTS:
                text = path.read_text(encoding="utf-8", errors="replace")
                if text.startswith(GENERATED_MARKER):
                    diagnostics.append(("DOC003", relative.as_posix(), "obsolete generated architecture document exists"))
    return diagnostics


def write_documents(manifest: dict[str, Any], manifest_path: Path) -> list[Path]:
    architecture_root = manifest_path.parent
    expected = render_documents(manifest)
    for relative in expected:
        destination = architecture_root / relative
        if destination.exists() and not destination.read_text(encoding="utf-8", errors="replace").startswith(GENERATED_MARKER):
            raise FileExistsError(f"refusing to overwrite non-generated document: {destination}")
    written: list[Path] = []
    for relative, content in expected.items():
        destination = architecture_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")
        written.append(destination)
    generated_root = architecture_root / "generated"
    if generated_root.is_dir():
        for path in generated_root.rglob("*.md"):
            relative = path.relative_to(architecture_root)
            if relative not in expected and relative not in EXTERNALLY_GENERATED_DOCUMENTS:
                text = path.read_text(encoding="utf-8", errors="replace")
                if text.startswith(GENERATED_MARKER):
                    path.unlink()
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        manifest = load_manifest(args.manifest)
        if args.write:
            for path in write_documents(manifest, args.manifest):
                print(path)
            return 0
        diagnostics = compare_documents(manifest, args.manifest)
        for rule_id, location, message in diagnostics:
            print(f"MUST {rule_id} {location}: {message}")
        print("PASS" if not diagnostics else "FAIL")
        return 0 if not diagnostics else 1
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


