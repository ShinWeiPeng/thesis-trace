def _flow_view(flow: dict[str, Any], labels: dict[str, str], manifest: dict[str, Any] | None = None) -> list[str]:
    lines = [f"### `{flow.get('id')}`", "", _escape(flow.get("description", "")), "", f"#### {labels['flow_diagram']}", "", "```mermaid", "sequenceDiagram"]
    modules = []
    owner = str(flow.get("owner"))
    for value in [owner] + [str(step.get("module")) for step in flow.get("steps", [])]:
        if value not in modules:
            modules.append(value)
    for module_id in modules:
        module = next(
            (
                item
                for item in (manifest or {}).get("modules", [])
                if isinstance(item, dict) and str(item.get("id")) == module_id
            ),
            {"id": module_id},
        )
        label = _module_diagram_label(
            manifest, module, include_level=False
        )
        lines.append(
            f"    participant {_node_id(module_id)} as {_mermaid_label(label)}"
        )
    previous = _node_id(owner)
    for step in flow.get("steps", []):
        current = _node_id(str(step.get("module")))
        arrow = "->>" if current == previous else "->>+"
        lines.append(f"    {previous}{arrow}{current}: {_mermaid_label(step.get('action', ''))}")
        emitted = step.get("emits", [])
        if emitted:
            lines.append(f"    Note right of {current}: {_mermaid_label(', '.join(str(item) for item in emitted))}")
        sync_query = next(
            (
                str(port.get("id"))
                for port in (manifest or {}).get("ports", [])
                if isinstance(port, dict)
                and str(port.get("id")) in step.get("receives", [])
                and port.get("kind") == "query"
                and port.get("description", {}).get("timing") == "sync"
            ),
            None,
        )
        if sync_query:
            lines.append(
                f"    {current}-->>-{previous}: {_mermaid_label(sync_query)} result"
            )
        elif current != previous:
            lines.append(f"    {current}-->>-{previous}: step {step.get('order')}")
            previous = current
    lines.append("```")
    lines.extend(["", f"#### {labels['steps']}", "", "| # | Module | Action | Receives | Emits | State changes | Side effects |", "|---|---|---|---|---|---|---|"])
    for step in flow.get("steps", []):
        lines.append(
            f"| {step.get('order')} | `{step.get('module')}` | {_escape(step.get('action', ''))} | "
            f"{_list_text(step.get('receives', []), labels['none'])} | {_list_text(step.get('emits', []), labels['none'])} | "
            f"{_escape('; '.join(str(item) for item in step.get('state_changes', [])) or labels['none'])} | "
            f"{_escape('; '.join(str(item) for item in step.get('side_effects', [])) or labels['none'])} |"
        )
    lines.extend(["", f"- **{labels['success']}:** {_escape(flow.get('success', {}).get('result', ''))}"])
    for error in flow.get("errors", []):
        error_ref = error.get("event") or error.get("code")
        lines.append(f"- **{labels['errors']}:** {_escape(error.get('condition'))} → `{_escape(error_ref)}` → {_escape(error.get('handling'))}")
    if manifest and manifest.get("schema_version") in SUPPORTED_SCHEMA_VERSIONS:
        workloads = [item for item in manifest.get("workloads", []) if item.get("flow") == flow.get("id")]
        if workloads:
            lines.extend(["", "#### Execution efficiency", ""])
            for workload in workloads:
                workload_id = str(workload.get("id"))
                profile_ids = sorted(
                    {
                        str(item.get("profile"))
                        for item in manifest.get("execution_mappings", [])
                        if item.get("workload") == workload_id
                    }
                )
                profile_links = [f"[`{profile_id}`](execution-{_file_name(profile_id)})" for profile_id in profile_ids]
                lines.append(
                    f"- Workload `{workload_id}`: `{workload.get('timing_class')}`; "
                    f"steps {_list_text(workload.get('steps', []), labels['none'])}; "
                    f"profiles {', '.join(profile_links) if profile_links else labels['none']}."
                )
    lines.append("")
    return lines


def _execution_view(manifest: dict[str, Any], profile: dict[str, Any]) -> list[str]:
    profile_id = str(profile.get("id"))
    units = [item for item in manifest.get("execution_units", []) if item.get("profile") == profile_id]
    mappings = [item for item in manifest.get("execution_mappings", []) if item.get("profile") == profile_id]
    channels = [item for item in manifest.get("execution_channels", []) if item.get("profile") == profile_id]
    data_profiles = [item for item in manifest.get("data_access_profiles", []) if item.get("profile") == profile_id]
    micro_profiles = [item for item in manifest.get("microarchitecture_profiles", []) if item.get("profile") == profile_id]
