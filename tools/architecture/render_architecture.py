def load_manifest(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise ValueError("manifest root must be a mapping")
    if data.get("schema_version") not in SUPPORTED_SCHEMA_VERSIONS:
        raise ValueError(
            "description views require schema_version 2.1.0 or 2.2.0"
        )
    return data


def _labels(manifest: dict[str, Any]) -> dict[str, str]:
    language = str(manifest.get("project", {}).get("documentation_language", "zh-TW")).lower()
    return LABELS["zh" if language.startswith("zh") else "en"]


def _escape(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _mermaid_label(value: Any) -> str:
    return str(value).replace('"', "'").replace("\n", " ")


def _node_id(value: str) -> str:
    return "n_" + re.sub(r"[^A-Za-z0-9_]", "_", value)


def _file_name(module_id: str) -> str:
    return module_id + ".md"


def _time_text(value: Any) -> str:
    if not isinstance(value, int) or isinstance(value, bool):
        return _escape(value)
    if value >= 1_000_000_000 and value % 1_000_000_000 == 0:
        return f"{value / 1_000_000_000:g} s ({value} ns)"
    if value >= 1_000_000 and value % 1_000_000 == 0:
        return f"{value / 1_000_000:g} ms ({value} ns)"
    if value >= 1_000 and value % 1_000 == 0:
        return f"{value / 1_000:g} us ({value} ns)"
    return f"{value} ns"


def _frequency_text(period_ns: Any) -> str:
    if not isinstance(period_ns, int) or isinstance(period_ns, bool) or period_ns <= 0:
        return "n/a"
    return f"{1_000_000_000 / period_ns:g} Hz"


def _list_text(values: list[Any], none_label: str) -> str:
    return ", ".join(f"`{_escape(item)}`" for item in values) if values else none_label


def _module_table(modules: list[dict[str, Any]], labels: dict[str, str]) -> list[str]:
    lines = [
        f"| ID | Level | Role | {labels['parent']} | {labels['status']} | {labels['purpose']} |",
        "|---|---|---|---|---|---|",
    ]
    for module in modules:
        purpose = module.get("description", {}).get("purpose", "")
        lines.append(
            f"| `{module.get('id')}` | {module.get('level')} | {module.get('role')} | "
            f"`{module.get('parent') or '-'}` | {module.get('implementation_status')} | {_escape(purpose)} |"
        )
    return lines


def _diagram_summary(
    manifest: dict[str, Any] | None, module: dict[str, Any]
) -> str:
    if not manifest or manifest.get("schema_version") != "2.2.0":
        return ""
    language = manifest.get("project", {}).get("diagram_language")
    summaries = module.get("description", {}).get("diagram_summaries", {})
    if not language or not isinstance(summaries, dict):
        return ""
    return str(summaries.get(str(language), ""))


def _module_diagram_label(
    manifest: dict[str, Any] | None,
    module: dict[str, Any],
    *,
    include_level: bool,
) -> str:
    module_id = str(module.get("id"))
    label = (
        f"{module_id} ({module.get('level')})"
        if include_level
        else module_id
    )
    summary = _diagram_summary(manifest, module)
    return f"{label}<br/>{summary}" if summary else label


def _structure_diagram(
    modules: list[dict[str, Any]],
    manifest: dict[str, Any] | None = None,
    include_dependencies: bool = True,
) -> list[str]:
    lines = ["```mermaid", "flowchart TD"]
    known = {str(module.get("id")) for module in modules}
    for module in modules:
        module_id = str(module.get("id"))
        label = _module_diagram_label(manifest, module, include_level=True)
        lines.append(f'    {_node_id(module_id)}["{_mermaid_label(label)}"]')
    for module in modules:
        module_id = str(module.get("id"))
        parent = module.get("parent")
        if parent in known:
            lines.append(f"    {_node_id(str(parent))} -->|owns| {_node_id(module_id)}")
        if include_dependencies:
            for target in module.get("depends_on", []):
                if target in known:
                    lines.append(f"    {_node_id(module_id)} -.->|depends| {_node_id(str(target))}")
    lines.append("```")
    return lines


def _function_guide(
    manifest: dict[str, Any], labels: dict[str, str]
) -> list[str]:
    modules = [
        item
        for item in manifest.get("modules", [])
        if isinstance(item, dict) and item.get("level") in {"L0", "L1", "L2"}
    ]
    flows = [
        item for item in manifest.get("flows", []) if isinstance(item, dict)
    ]
    lines: list[str] = []
    for module in modules:
        module_id = str(module.get("id"))
        description = module.get("description", {})
        children = [
            str(item.get("id"))
            for item in modules
            if item.get("parent") == module_id
        ]
        related = [
            flow
            for flow in flows
            if flow.get("owner") == module_id
            or any(
                step.get("module") == module_id
                for step in flow.get("steps", [])
                if isinstance(step, dict)
            )
        ]
        flow_links = [
            (
                f"[`{flow.get('id')}`]"
                f"(generated/{_file_name(str(flow.get('owner')))}"
                f"#{str(flow.get('id')).replace('.', '')})"
            )
            for flow in related
        ]
        lines.extend(
            [
                f"### `{module_id}`",
                "",
                f"- **{labels['purpose']}:** "
                f"{_escape(description.get('purpose', ''))}",
                f"- **{labels['children']}:** "
                f"{_list_text(children, labels['none'])}",
                f"- **{labels['related_flows']}:** "
                f"{', '.join(flow_links) if flow_links else labels['none']}",
            ]
        )
        rationale = [
            _escape(value) for value in description.get("invariants", [])
        ]
        rationale.extend(
            (
                f"{_escape(error.get('condition', ''))} → "
                f"{_escape(error.get('handling', ''))}"
            )
            for error in description.get("errors", [])
            if isinstance(error, dict)
        )
        lines.extend(
            [
                f"- **{labels['protection_rationale']}:** "
                f"{'; '.join(rationale) if rationale else labels['none']}",
                "",
            ]
        )
    return lines


def _code_links(entries: list[dict[str, Any]], prefix: str, none_label: str) -> str:
    if not entries:
        return none_label
    values = []
    for entry in entries:
        path = str(entry.get("path", ""))
        symbol = str(entry.get("symbol", ""))
        kind = str(entry.get("kind", ""))
        values.append(f"[`{symbol}`]({prefix}{path}) ({kind})")
    return "<br>".join(values)


def _module_card(module: dict[str, Any], labels: dict[str, str], prefix: str) -> list[str]:
    description = module.get("description", {})
    none = labels["none"]
    lines = [f"### `{module.get('id')}`", ""]
    lines.extend(
        [
            f"- **{labels['purpose']}:** {_escape(description.get('purpose', ''))}",
            f"- **{labels['parent']}:** `{module.get('parent') or '-'}`",
            f"- **{labels['status']}:** `{module.get('implementation_status')}`",
            f"- **{labels['inputs']}:** {_list_text(description.get('input_ports', []), none)}",
            f"- **{labels['outputs']}:** {_list_text(description.get('output_ports', []), none)}",
            f"- **{labels['events']}:** {_list_text(description.get('emitted_events', []), none)}",
        ]
    )
    states = description.get("owned_state", [])
    lines.append(
        f"- **{labels['state']}:** "
        + ("; ".join(f"`{_escape(item.get('name'))}` — {_escape(item.get('description'))}" for item in states) if states else none)
    )
    effects = description.get("side_effects", [])
    lines.append(
        f"- **{labels['effects']}:** "
        + ("; ".join(f"{_escape(item.get('description'))} (`{_escape(item.get('via_port', '-'))}`)" for item in effects) if effects else none)
    )
    errors = description.get("errors", [])
    lines.append(
        f"- **{labels['errors']}:** "
        + ("; ".join(f"`{_escape(item.get('id'))}`: {_escape(item.get('condition'))} → `{_escape(item.get('event'))}` → {_escape(item.get('handling'))}" for item in errors) if errors else none)
    )
    lines.append(f"- **{labels['invariants']}:** " + ("; ".join(_escape(item) for item in description.get("invariants", [])) or none))
    lines.append(f"- **{labels['entrypoints']}:** {_code_links(module.get('entrypoints', []), prefix, none)}")
    lines.append(f"- **{labels['contracts']}:** {_code_links(module.get('public_symbols', []), prefix, none)}")
    lines.append("")
    return lines


